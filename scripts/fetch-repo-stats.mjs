/**
 * Regenerates data/repoStats.ts from the live GitHub API.
 *
 * The Open Ontologies figures on /research/open-source were typed by hand and
 * were 14 stars, 3 forks and 4 merged pull requests behind reality within a
 * fortnight. A number that only a person can refresh is a number that goes
 * stale, on a page whose whole argument is that the reader can check us.
 *
 * Unlike fetch-contributions.mjs this uses plain fetch rather than the gh CLI,
 * so it can run anywhere a build runs. It authenticates with GITHUB_TOKEN or
 * GH_TOKEN when one is set, and falls back to the unauthenticated API, which
 * allows 60 requests an hour per address and needs two.
 *
 * It FAILS SOFT. If GitHub is down, rate-limits us or answers with anything
 * unexpected, the existing data/repoStats.ts is left exactly as it is and the
 * process exits 0, so a deploy never breaks over a statistic.
 *
 * Usage: npm run stats
 */

import { writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, '..', 'data', 'repoStats.ts');

const REPO = 'fabio-rovai/open-ontologies';
const AUTHOR = 'fabio-rovai';

const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
const headers = {
  Accept: 'application/vnd.github+json',
  'User-Agent': 'tesseract-gov-website',
  ...(token ? { Authorization: `Bearer ${token}` } : {}),
};

async function get(url) {
  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return res.json();
}

try {
  const repo = await get(`https://api.github.com/repos/${REPO}`);
  // Merged pull requests whose author is somebody other than us. The search
  // API returns the count directly, so this stays one request rather than
  // paging the whole pull request history.
  const query = encodeURIComponent(`repo:${REPO} is:pr is:merged -author:${AUTHOR}`);
  const merged = await get(`https://api.github.com/search/issues?q=${query}&per_page=1`);

  const stars = repo.stargazers_count;
  const forks = repo.forks_count;
  const outsideMergedPullRequests = merged.total_count;

  if (![stars, forks, outsideMergedPullRequests].every((n) => Number.isInteger(n) && n >= 0)) {
    throw new Error('GitHub returned something that is not a count');
  }

  const generatedOn = new Date().toISOString().slice(0, 10);
  writeFileSync(
    OUT,
    `// GENERATED by scripts/fetch-repo-stats.mjs. Do not edit by hand.
// Live figures for the Open Ontologies repository. Regenerate with
// \`npm run stats\`.

export interface RepoStats {
  stars: number;
  forks: number;
  outsideMergedPullRequests: number;
  generatedOn: string;
}

export const OPEN_ONTOLOGIES_STATS: RepoStats = ${JSON.stringify(
      { stars, forks, outsideMergedPullRequests, generatedOn },
      null,
      2,
    )};
`,
    'utf8',
  );
  console.log(`Wrote ${OUT}`);
  console.log({ stars, forks, outsideMergedPullRequests, generatedOn });
} catch (error) {
  console.warn(`Could not refresh repo stats, keeping the committed figures: ${error.message}`);
  if (!token) console.warn('Set GITHUB_TOKEN to raise the unauthenticated rate limit of 60 requests an hour.');
}
