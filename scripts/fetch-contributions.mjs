/**
 * Regenerates data/contributionTotals.ts from the live GitHub API.
 *
 * The narrative rows in data/contributions.ts are hand-written, because a
 * finding needs a sentence a reader can act on. The counts are not: they are
 * derived here so they cannot go stale, and so nobody has to defend a number
 * on the site that GitHub no longer agrees with.
 *
 * Counted: issues and pull requests authored by AUTHOR in repositories owned
 * by somebody else. Excluded, deliberately:
 *   - our own repositories, which are the "projects maintained" story
 *   - repositories belonging to our own people and clients, which are work
 *   - the April 2026 Tardygrada outreach pull requests, which were closed
 *     unmerged and are not a credential
 *
 * Usage: npm run contributions   (requires the gh CLI, authenticated)
 */

import { execFileSync } from 'child_process';
import { writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, '..', 'data', 'contributionTotals.ts');

const AUTHOR = 'fabio-rovai';
const EXCLUDED_OWNERS = new Set([
  'fabio-rovai',      // own projects
  'stelios12312312',  // co-founder, company work
  'linstan1',         // this website
  'raluca07',         // client work
]);
// Closed unmerged outreach pull requests, April 2026. Every one opens with
// "Your <n> lines in <n> verified instructions", which is the signature.
const isOutreachPr = (title) => /^Your .*verified instructions \(Tardygrada\)$/.test(title);

function search(page) {
  const out = execFileSync('gh', [
    'api', '-X', 'GET', 'search/issues',
    '-f', `q=author:${AUTHOR}`,
    '-f', 'per_page=100',
    '-f', `page=${page}`,
  ], { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
  return JSON.parse(out).items ?? [];
}

const items = [];
for (let page = 1; page <= 10; page += 1) {
  const batch = search(page);
  items.push(...batch);
  if (batch.length < 100) break;
}

const external = items.filter((item) => {
  const repo = item.repository_url.replace(/.*\/repos\//, '');
  const owner = repo.split('/')[0];
  if (EXCLUDED_OWNERS.has(owner)) return false;
  if (item.pull_request && isOutreachPr(item.title)) return false;
  return true;
});

const repos = new Set(external.map((i) => i.repository_url.replace(/.*\/repos\//, '')));
const owners = new Set([...repos].map((r) => r.split('/')[0]));
const prs = external.filter((i) => i.pull_request);
const merged = prs.filter((i) => i.pull_request.merged_at);
const openPrs = prs.filter((i) => i.state === 'open');
const issues = external.filter((i) => !i.pull_request);

const totals = {
  mergedPullRequests: merged.length,
  openPullRequests: openPrs.length,
  issuesFiled: issues.length,
  projects: repos.size,
  organisations: owners.size,
  generatedOn: new Date().toISOString().slice(0, 10),
};

const body = `// GENERATED by scripts/fetch-contributions.mjs. Do not edit by hand.
// Counts issues and pull requests authored by ${AUTHOR} in repositories owned
// by other people, excluding closed outreach pull requests. Regenerate with
// \`npm run contributions\`.

export interface ContributionTotals {
  mergedPullRequests: number;
  openPullRequests: number;
  issuesFiled: number;
  projects: number;
  organisations: number;
  generatedOn: string;
}

export const CONTRIBUTION_TOTALS: ContributionTotals = ${JSON.stringify(totals, null, 2)};
`;

writeFileSync(OUT, body);
console.log(`Wrote ${OUT}`);
console.log(totals);
